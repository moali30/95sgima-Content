"""Same data, two methods: CB-SEM (ML, like AMOS) vs PLS-SEM (like SmartPLS default).

Model: X -> Y, true standardized path = 0.50, 3 indicators per construct.
Scenario A: data generated by a common factor model (reflective, loadings 0.70).
Scenario B: data generated by a composite model (construct = weighted sum of indicators).
Each scenario: n = 300, 1000 replications, seed 95.
"""
import numpy as np
from scipy.optimize import minimize

SEED, N, REPS, BETA = 95, 300, 1000, 0.50
rng = np.random.default_rng(SEED)


def factor_population(lam=0.7, beta=BETA):
    L = np.zeros((6, 2)); L[:3, 0] = lam; L[3:, 1] = lam
    Phi = np.array([[1, beta], [beta, 1]])
    Theta = np.diag(np.full(6, 1 - lam**2))
    return L @ Phi @ L.T + Theta


def composite_population(beta=BETA):
    # unequal within-block correlations, unequal weights (a formative-style composite)
    R = np.array([[1, .2, .4], [.2, 1, .5], [.4, .5, 1]])
    w = np.array([.6, .3, .4])
    w = w / np.sqrt(w @ R @ w)          # composite has variance 1
    S = np.zeros((6, 6)); S[:3, :3] = R; S[3:, 3:] = R
    S[:3, 3:] = beta * np.outer(R @ w, R @ w); S[3:, :3] = S[:3, 3:].T
    return S


def pls(X):
    """PLS-SEM, mode A, path weighting scheme; returns path, loadings, PLSc path."""
    Z = (X - X.mean(0)) / X.std(0)
    b = [slice(0, 3), slice(3, 6)]
    w = [np.ones(3), np.ones(3)]
    for _ in range(300):
        s = [Z[:, b[k]] @ w[k] for k in range(2)]
        s = [v / v.std() for v in s]
        r = np.corrcoef(s[0], s[1])[0, 1]
        inner = [r * s[1], r * s[0]]          # path weighting with 2 constructs
        new = [Z[:, b[k]].T @ inner[k] / len(Z) for k in range(2)]
        new = [v / (Z[:, b[k]] @ v).std() for k, v in enumerate(new)]
        if max(np.abs(new[k] - w[k]).max() for k in range(2)) < 1e-7:
            w = new; break
        w = new
    s = [Z[:, b[k]] @ w[k] for k in range(2)]
    s = [v / v.std() for v in s]
    path = np.corrcoef(s[0], s[1])[0, 1]
    load = np.concatenate([[np.corrcoef(Z[:, j], s[k])[0, 1] for j in range(b[k].start, b[k].stop)] for k in range(2)])
    # PLSc (Dijkstra & Henseler 2015): rho_A correction
    rhoA = []
    for k in range(2):
        S = np.corrcoef(Z[:, b[k]].T); ww = w[k] / np.sqrt(w[k] @ S @ w[k])  # scaled so composite variance = 1
        num = ww @ (S - np.diag(np.diag(S))) @ ww
        den = ww @ (np.outer(ww, ww) - np.diag(ww**2)) @ ww
        rhoA.append((ww @ ww) ** 2 * num / den)
    return path, load, path / np.sqrt(rhoA[0] * rhoA[1])


def cbsem(X):
    """CB-SEM by maximum likelihood (two-factor model, factor variances fixed to 1)."""
    S = np.cov(X.T, bias=True); p = 6
    logdetS = np.linalg.slogdet(S)[1]

    def implied(t):
        L = np.zeros((6, 2)); L[:3, 0] = t[:3]; L[3:, 1] = t[3:6]
        Phi = np.array([[1, t[12]], [t[12], 1]])
        return L @ Phi @ L.T + np.diag(t[6:12])

    def f(t):
        Sig = implied(t)
        sign, ld = np.linalg.slogdet(Sig)
        if sign <= 0:
            return 1e6
        return ld + np.trace(S @ np.linalg.inv(Sig)) - logdetS - p

    sd = np.sqrt(np.diag(S))
    t0 = np.concatenate([0.7 * sd, 0.5 * sd**2, [0.3]])
    bounds = [(1e-3, None)] * 6 + [(1e-4, None)] * 6 + [(-0.999, 0.999)]
    res = minimize(f, t0, method="L-BFGS-B", bounds=bounds)
    t = res.x
    std_load = t[:6] / sd
    chi2 = (N - 1) * res.fun
    return t[12], std_load, chi2


def run(name, Sigma):
    Lc = np.linalg.cholesky(Sigma)
    out = {"pls": [], "plsc": [], "cb": [], "pls_load": [], "cb_load": [], "chi2": []}
    for _ in range(REPS):
        X = rng.standard_normal((N, 6)) @ Lc.T
        p, pl, pc = pls(X)
        c, cl, chi2 = cbsem(X)
        out["pls"].append(p); out["plsc"].append(pc); out["cb"].append(c)
        out["pls_load"].append(pl.mean()); out["cb_load"].append(cl.mean()); out["chi2"].append(chi2)
    o = {k: np.array(v) for k, v in out.items()}
    print(f"\n== {name} (n = {N}, {REPS} reps, true path = {BETA}) ==")
    for k, lab in [("cb", "CB-SEM (ML)"), ("pls", "PLS-SEM"), ("plsc", "PLSc")]:
        lo, hi = np.percentile(o[k], [2.5, 97.5])
        print(f"{lab:12s} path mean = {o[k].mean():.3f}  95% of reps in [{lo:.3f}, {hi:.3f}]  bias = {o[k].mean()-BETA:+.3f}")
    print(f"mean loading: CB-SEM = {o['cb_load'].mean():.3f}, PLS-SEM = {o['pls_load'].mean():.3f}")
    # chi-square df = 21 - 13 = 8; critical value at .05 = 15.507
    print(f"CB-SEM chi2 (df = 8) mean = {o['chi2'].mean():.1f}; rejected at .05 in {np.mean(o['chi2'] > 15.507):.1%} of reps")
    return o


if __name__ == "__main__":
    A = run("Scenario A: common factor data (reflective, loadings 0.70)", factor_population())
    B = run("Scenario B: composite data (weighted sum of indicators)", composite_population())
    # one single dataset for the reel: same data, two answers
    rng1 = np.random.default_rng(SEED)
    X = rng1.standard_normal((N, 6)) @ np.linalg.cholesky(factor_population()).T
    p, _, pc = pls(X); c, _, _ = cbsem(X)
    print(f"\n== One dataset (Scenario A, n = {N}, seed {SEED}) ==\nCB-SEM path = {c:.2f}, PLS-SEM path = {p:.2f}, PLSc path = {pc:.2f}")
